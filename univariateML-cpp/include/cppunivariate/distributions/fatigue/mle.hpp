enum class FatigueStatus { Ok, InvalidInput, Unbounded, SearchFailure };

struct FatigueResult {
  double alpha;
  double beta;
  double logLik;
  int iterations;
  FatigueStatus status = FatigueStatus::Ok;
  StopDetail stop_detail{};
};

#include "certificate.hpp"

// Historical Newton proposer retained for golden compatibility. The complete
// rational inclusion below decides whether it represents the winning root.
inline FatigueResult fatigue_proposal_impl(span x, double tol, int maxit, bool standardized) {
  maxit = static_cast<int>(solver_budget(maxit));
  constexpr double kNaN = std::numeric_limits<double>::quiet_NaN();
  const std::size_t n = x.size();
  if (n == 0) return {0.0, 0.0, kNaN, 0, FatigueStatus::InvalidInput};

  bool constant = true;
  double unit = 0.0;
  for (auto v : x) { constant = constant && v == x[0]; unit = std::max(unit,v); }
  if (constant) return {kNaN,kNaN,kNaN,0,FatigueStatus::Unbounded};
  if (unit > 0.0 && std::isfinite(unit) && !standardized) {
    std::vector<double> y(n);
    for (std::size_t i=0;i<n;++i) {
      y[i]=x[i]/unit;
      if (!(y[i]>0.0)) return {kNaN,kNaN,kNaN,0};
    }
    const auto r=fatigue_proposal_impl(span{y.data(),n},tol,maxit,true);
    return {r.alpha,r.beta*unit,r.logLik-static_cast<double>(n)*std::log(unit),r.iterations,r.status};
  }

  const double dn = static_cast<double>(n);
  double sum_x = 0.0, sum_sqrt_x = 0.0, sum_inv_sqrt_x = 0.0;
  CPPUNIV_EXTENDED_REAL sum_inv_x = CPPUNIV_EXTENDED_LITERAL(0.0,0.0L);
  for (auto v : x) {
    sum_x += v;
    sum_inv_x += CPPUNIV_EXTENDED_LITERAL(1.0,1.0L) / v;
    const double sx = std::sqrt(v);
    sum_sqrt_x += sx;
    sum_inv_sqrt_x += 1.0 / sx;
  }
  const double x_bar = sum_x / dn;
  const double x_inv_bar = dn / sum_inv_x;

  auto f_over_df = [&](double beta) {
    CPPUNIV_EXTENDED_REAL sum_xb = CPPUNIV_EXTENDED_LITERAL(0.0,0.0L), sum_xb_sq = CPPUNIV_EXTENDED_LITERAL(0.0,0.0L);
    for (auto v : x) {
      const CPPUNIV_EXTENDED_REAL xb = CPPUNIV_EXTENDED_LITERAL(1.0,1.0L) / (static_cast<CPPUNIV_EXTENDED_REAL>(v) + beta);
      sum_xb += xb;
      sum_xb_sq += xb * xb;
    }
    const CPPUNIV_EXTENDED_REAL xi = dn / sum_xb;
    const CPPUNIV_EXTENDED_REAL dxi = sum_xb_sq * xi * xi / dn;
    const CPPUNIV_EXTENDED_REAL f =
        static_cast<CPPUNIV_EXTENDED_REAL>(beta) * beta - beta * (2.0 * x_inv_bar + xi) + x_inv_bar * (x_bar + xi);
    const CPPUNIV_EXTENDED_REAL df =
        2.0 * beta - (2.0 * x_inv_bar + xi) - beta * dxi + x_inv_bar * dxi;
    return static_cast<double>(f / df);
  };

  // Method-of-moments start.
  const double beta0 = sum_sqrt_x / sum_inv_sqrt_x;
  auto nr = cppunivariate::newton_raphson_1d(beta0, f_over_df, tol, maxit);
  double beta = nr.x;
  if (!(beta>0.0) || !std::isfinite(beta) || !nr.converged) {
    // The profile root lies between harmonic and arithmetic means.
    double lo=x_inv_bar, hi=x_bar;
    for (int j=0;j<maxit;++j) {
      const double mid=std::sqrt(lo)*std::sqrt(hi);
      CPPUNIV_EXTENDED_REAL inv=CPPUNIV_EXTENDED_LITERAL(0.0,0.0L);
      for (auto v:x) inv+=CPPUNIV_EXTENDED_LITERAL(1.0,1.0L)/(static_cast<CPPUNIV_EXTENDED_REAL>(v)+mid);
      const CPPUNIV_EXTENDED_REAL xi=dn/inv;
      const CPPUNIV_EXTENDED_REAL f=static_cast<CPPUNIV_EXTENDED_REAL>(mid)*mid-mid*(2.0*x_inv_bar+xi)+x_inv_bar*(x_bar+xi);
      if (f>0.0) lo=mid; else hi=mid;
    }
    if (hi-lo > 1e-12*hi)
      return {kNaN,kNaN,kNaN,nr.iterations,FatigueStatus::SearchFailure};
    beta=std::sqrt(lo)*std::sqrt(hi);
  }
  // Standard Birnbaum-Saunders α-MLE FOC: α² = x̄/β + β/H(x) − 2, where
  // H(x) = n/Σ(1/x_i) is the harmonic mean. The −2 was missing in the
  // historical R code this was ported from; the bug shipped silently
  // for years because the goldens and existing tests were generated by
  // (and self-consistent against) the buggy fitter. The AI-first
  // validation harness flagged it on 2026-05-10 by symbolically
  // deriving the score from the standard BS density and finding it
  // ≈ 30 at the recovered α — see roadmap/2026-05-10-fatigue-cost-mismatch.md
  // for the full investigation.
  CPPUNIV_EXTENDED_REAL alpha_sq=CPPUNIV_EXTENDED_LITERAL(0.0,0.0L);
  for (auto v:x) {
    const CPPUNIV_EXTENDED_REAL d=(static_cast<CPPUNIV_EXTENDED_REAL>(v)-beta)/std::sqrt(static_cast<CPPUNIV_EXTENDED_REAL>(v))/std::sqrt(static_cast<CPPUNIV_EXTENDED_REAL>(beta));
    alpha_sq+=d*d;
  }
  const double alpha=static_cast<double>(std::sqrt(alpha_sq/dn));

  double logLik = 0.0;
  for (auto v : x) {
    const double sx = std::sqrt(v) / std::sqrt(beta);
    const double sy = std::sqrt(beta) / std::sqrt(v);
    const double z = static_cast<double>((static_cast<CPPUNIV_EXTENDED_REAL>(v)-beta)/std::sqrt(static_cast<CPPUNIV_EXTENDED_REAL>(v))/std::sqrt(static_cast<CPPUNIV_EXTENDED_REAL>(beta))/alpha);
    const double log_pref = std::log(sx + sy) - std::log(2.0 * alpha) - std::log(v);
    const double log_phi = cppunivariate::special::dnorm(z, 0.0, 1.0, 1);
    logLik += log_pref + log_phi;
  }
  return {alpha, beta, logLik, nr.iterations};
}

// With beta held, alpha has its exact RMS solution. With alpha held,
// certify every beta-profile maximum (the profile can be multimodal).
inline FatigueResult fatigue_mle(span x, double tol, int maxit,
    double held_alpha = std::numeric_limits<double>::quiet_NaN(),
    double held_beta = std::numeric_limits<double>::quiet_NaN()) {
  maxit = static_cast<int>(solver_budget(maxit));
  const bool fa=!std::isnan(held_alpha), fb=!std::isnan(held_beta);
  if (!fa && !fb) {
    auto certified=fatigue_certificate::fit(x,tol,maxit,held_alpha,held_beta);
    if(certified.status!=FatigueStatus::Ok)return certified;
    const auto proposal=fatigue_proposal_impl(x,tol,maxit,false);
    if(proposal.status==FatigueStatus::Ok&&proposal.alpha>0&&proposal.beta>0&&
       std::isfinite(proposal.logLik)&&std::abs(std::log(proposal.beta/certified.beta))<=1e-8&&
       std::abs(std::log(proposal.alpha/certified.alpha))<=1e-8&&
       std::abs(proposal.logLik-certified.logLik)<=1e-10*x.size()) {
      certified.alpha=proposal.alpha;certified.beta=proposal.beta;certified.logLik=proposal.logLik;
    }
    return certified;
  }
  const double nan=std::numeric_limits<double>::quiet_NaN();
  if (x.empty() || !(tol>0) || !std::isfinite(tol) || maxit<=0 ||
      (fa && (!(held_alpha>0)||!std::isfinite(held_alpha))) ||
      (fb && (!(held_beta>0)||!std::isfinite(held_beta)))) return {nan,nan,nan,0,FatigueStatus::InvalidInput};
  return fatigue_certificate::fit(x,tol,maxit,held_alpha,held_beta);
}

