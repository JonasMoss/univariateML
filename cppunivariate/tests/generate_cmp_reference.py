#!/usr/bin/env python3
"""Independent CMP references, mpmath >=50 digits, no third-party C++ code.
Small modes: sum the original weights (not the C++ residual recurrence).
Large modes: integrate the lgamma summand at 70+ digits around its saddle;
Poisson summation error is negligible at the selected widths, but this is
numerical validation, not an interval proof of the integral/sum difference.
Inputs are the exact binary64 eta and nu passed to C++.
Run via /tmp/umvl-cpu/run python3 cppunivariate/tests/generate_cmp_reference.py.
"""
import math
from pathlib import Path
import mpmath as mp


def reference(eta, nu):
    mp.mp.dps = 70
    e, n = mp.mpf(eta), mp.mpf(nu)
    z = mp.exp(e/n)
    mp.mp.dps = max(70, int(mp.log10(max(z, 1)))+75)
    e, n = mp.mpf(eta), mp.mpf(nu)
    z = mp.exp(e/n)
    mode = mp.floor(z)
    a = mp.log(mode+1)
    h0 = mp.loggamma(mode+1)
    f0 = mode*e-n*h0
    if z < 1e6:
        # Independent direct lgamma evaluations, including a full lower tail.
        sums = [mp.mpf(0) for _ in range(6)]
        k = 0
        while True:
            h = mp.loggamma(k+1)
            w = mp.exp(k*e-n*h-f0)
            d = k-mode
            r = h-h0-a*d
            for i, v in enumerate([1, d, r, d*d, r*r, d*r]):
                sums[i] += w*v
            if k > mode and w*(1+k**4) < mp.mpf('1e-60')*sums[0]:
                break
            k += 1
    else:
        width = mp.sqrt(z/n)
        # Center at z, which differs from the true saddle only by O(1).
        mode = z
        a = mp.log(z)
        h0 = mp.loggamma(z+1)
        f0 = z*e-n*h0
        def integrand(y, p):
            d = width*y
            h = mp.loggamma(z+d+1)
            r = h-h0-a*d
            w = mp.exp(d*e-n*(h-h0))
            return w*[1, d, r, d*d, r*r, d*r][p]*width
        sums = [mp.quad(lambda y: integrand(y, p), [-20,-10,-5,0,5,10,20]) for p in range(6)]
    s, d, r, dd, rr, dr = sums
    d, r = d/s, r/s
    vd, vr, cr = dd/s-d*d, rr/s-r*r, dr/s-d*r
    return [f0+mp.log(s), mode+d, vd, h0+a*d+r,
            a*a*vd+2*a*cr+vr, a*vd+cr]


def main():
    rows = []
    grid = [(l,n) for l in [1e-12,1e-3,.5,.9,.99,1,2,10,1000]
            for n in [.01,.05,.075,.3,1,2,10,100]]
    grid += [(4,2)]
    for lam, nu in grid:
        eta = math.log(lam)
        result = reference(eta, nu)
        rows.append('    {'+', '.join([repr(eta),repr(nu)]+[mp.nstr(v,22) for v in result])+'},')
        print(lam, nu, flush=True)
    dest = Path(__file__).with_name('cmp_reference.inc')
    dest.write_text('// Generated by generate_cmp_reference.py; exact binary64 inputs.\n'+ '\n'.join(rows)+'\n')

if __name__ == '__main__':
    main()
