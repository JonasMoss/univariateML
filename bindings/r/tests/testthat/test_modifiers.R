test_that("truncated d/p/q evaluate vectors elementwise (TASK-216)", {
  # A scalar window bound used to decide the tail branch for the whole vector,
  # so pml() repeated its first value.
  x <- c(2, 2, 3, 3, 3, 4, 5, 5, 6, 7)
  fits <- list(
    geom = mlgeom(x, truncate = c(2, 7)),
    nbinom = mlnbinom(x, size = 2, truncate = c(2, 7)),
    pois = mlpois(x, truncate = c(2, 7)))
  for (id in names(fits)) {
    fit <- fits[[id]]
    q <- 1:8
    for (lower in c(TRUE, FALSE)) for (log.p in c(TRUE, FALSE)) {
      whole <- pml(q, fit, lower.tail = lower, log.p = log.p)
      each <- vapply(q, function(v) pml(v, fit, lower.tail = lower, log.p = log.p), numeric(1))
      expect_identical(whole, each, info = paste(id, lower, log.p))
    }
    # The conditional CDF is the running sum of the conditional masses.
    expect_equal(pml(2:7, fit), cumsum(dml(2:7, fit)), tolerance = 1e-12, info = id)
    expect_equal(pml(7, fit), 1, info = id)
    p <- c(0.1, 0.5, 0.9)
    expect_identical(qml(p, fit), vapply(p, function(v) qml(v, fit), numeric(1)), info = id)
  }
})

modifier_quantile_reached <- function(value,p,lower,log) {
  e<-64*.Machine$double.eps
  target<-if(log) {
    if(lower)ifelse(p > -.Machine$double.xmax/(1+e),p*(1+e),p) else p*(1-e)
  } else if(lower)p*(1-e) else ifelse(1-p>4*e,p*(1+e),p)
  if(lower)value>=target else value<=target
}

# Every retained parameter point, through the public configured base model.
modifier_roundtrip_cases <- function() {
  pairs<-list(pois=c("ztpois","zmpois","zip","tpois"),
              binom=c("ztbinom","zmbinom","zib","tbinom"),
              nbinom=c("ztnbinom","zmnbinom","zinb"),
              geom=c("ztgeom","zmgeom"),lgser="zmlogarithmic",zeta="zipf")
  cases<-list()
  add<-function(id,args,config,centre,label) {
    cases[[length(cases)+1L]]<<-list(id=id,args=args,config=config,centre=centre,label=label)
  }
  for(base in names(pairs))for(id in pairs[[base]]) {
    t<-jsonlite::fromJSON(file.path("fixtures",paste0(".modifier_",id),"truth.json"),simplifyVector=FALSE)
    matrix_of<-function(rows)do.call(rbind,lapply(rows,function(row)vapply(row,as.numeric,numeric(1))))
    t$parameters<-matrix_of(t$parameters);t$quantiles<-matrix_of(t$quantiles)
    t$parameter_names<-unlist(t$parameter_names)
    for(i in seq_len(nrow(t$parameters))) {
      args<-as.list(setNames(t$parameters[i,],t$parameter_names))
      med<-t$quantiles[t$quantiles[,1]==i-1 & t$quantiles[,2]==1 & t$quantiles[,3]==0 & t$quantiles[,4]==.5,5]
      centre<-if(length(med) && is.finite(med[1]) && abs(med[1])<2^53-101)floor(med[1]) else 0
      if(id=="zipf") {config<-list(truncate=c(1,args$N));args$N<-NULL
      } else if(id %in% c("tpois","tbinom")) {
        config<-list(truncate=c(args$a+1,args$b));args$a<-args$b<-NULL
      } else config<-list(zero=if(startsWith(id,"zt"))"truncated" else if(startsWith(id,"zm"))"modified" else "inflated")
      if(base=="lgser"){args$theta<-args$prob;args$prob<-NULL}
      add(base,args,config,centre,paste(id,i))
      if(id %in% c("ztpois","ztbinom","ztnbinom","ztgeom","zmlogarithmic")) {
        ordinary<-args;ordinary$p0<-NULL
        add(base,ordinary,list(zero="none"),4,paste(base,"none",i))
      }
      if(id %in% c("ztpois","ztbinom","ztgeom","ztnbinom"))for(window in list(c(2,12),c(2,Inf),c(0,5),c(0,Inf)))
        add(base,args,list(truncate=window),4,paste(base,"window",i,paste(window,collapse=":")))
      if(id=="ztgeom")for(pi in c(0,.25,.5,1))
        add(base,c(args,list(pi=pi)),list(zero="inflated"),4,paste(base,"inflated",i,pi))
    }
  }
  for(s in c(0,-1,-2,2))add("zeta",list(s=s),list(truncate=c(1,8)),4,paste("zeta",s))
  cases
}
test_that("every discrete modifier configuration round trips in four modes", {
  for(case in modifier_roundtrip_cases()) {
    window<-case$config$truncate
    if(!is.null(window) && case$id!="zeta") {
      args<-case$args
      point<-if(case$id=="pois" && args$lambda==0 ||
                case$id %in% c("geom","nbinom") && args$prob==1 ||
                case$id=="nbinom" && args$size==0 ||
                case$id=="binom" && (args$prob==0 || args$size==0))0 else
        if(case$id=="binom" && args$prob==1)args$size else NA_real_
      empty<-case$id=="binom" && window[1]>args$size ||
        !is.na(point) && (point<window[1] || point>window[2])
      if(empty) {
        expect_error(do.call(get(paste0("ml",case$id)),c(args,case$config)),
                     "zero or unresolved probability|evaluation failed|empty|invalid",info=case$label)
        next
      }
    }
    # These are inherited evaluator/domain refusals, recorded before the
    # quantile change; do not count an unconstructed law as a round trip.
    if(case$id=="nbinom" && !is.null(window) && is.finite(window[2]) &&
       window[2]<=12 && case$args$size==1e8 && case$args$prob==.5) {
      expect_error(do.call(mlnbinom,c(case$args,case$config)),
                   "Conditional normalization cannot be resolved",info=case$label)
      next
    }
    if(case$id=="lgser" && identical(case$config$zero,"none") && case$args$theta==0) {
      expect_error(do.call(mllgser,c(case$args,case$config)),"held `theta`",info=case$label)
      next
    }
    fit<-do.call(get(paste0("ml",case$id)),c(case$args,case$config))
    for(lower in c(TRUE,FALSE))for(log in c(FALSE,TRUE)) {
      k<-case$centre+(if(grepl(" window ",case$label,fixed=TRUE))(-2:2) else (-100:100))
      p<-pml(k,fit,lower.tail=lower,log.p=log)
      previous<-pml(k-1,fit,lower.tail=lower,log.p=log)
      eligible<-if(log)is.finite(p)&p<0 else p>0&p<1
      eligible<-eligible & !is.na(p!=previous) & p!=previous
      k<-k[eligible];p<-p[eligible];previous<-previous[eligible]
      q<-qml(p,fit,lower.tail=lower,log.p=log)
      info<-paste(case$label,lower,log)
      expect_true(all(is.finite(q) & q<=k),info=info)
      expect_true(all(modifier_quantile_reached(pml(q,fit,lower.tail=lower,log.p=log),p,lower,log)),info=info)
      expect_true(all(!modifier_quantile_reached(pml(q-1,fit,lower.tail=lower,log.p=log),p,lower,log)),info=info)
      expect_true(all(q==k | modifier_quantile_reached(previous,p,lower,log)),info=info)
    }
  }
})

