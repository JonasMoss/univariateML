test_that("conditional geometric rational jumps use the conditional band", {
  # On [2,5], geometric(prob=1/2) has masses (8,4,2,1)/15.
  fit<-mlgeom(prob=.5,truncate=c(2,5))
  for(lower in c(TRUE,FALSE))for(log in c(FALSE,TRUE)) {
    p<-if(lower)c(8,12,14)/15 else c(7,3,1)/15
    if(log)p<-base::log(p)
    expect_equal(qml(p,fit,lower.tail=lower,log.p=log),as.numeric(2:4))
  }
})

test_that("conditional integer expansion retains a finite last bracket", {
  fit<-mlgeom(prob=1e-308,truncate=c(0,Inf))
  q<-qml(.8,fit)
  expect_true(is.finite(q))
  expected<--log1p(-.8*(1-64*.Machine$double.eps))
  expect_equal(q*1e-308,expected,tolerance=1e-14)
  expect_true(modifier_quantile_reached(pml(q,fit),.8,TRUE,FALSE))
})
