test_that("every estimate exposes outcome flags on the vector and object", {
  fit <- mlnorm(c(-1,0,1))
  expect_identical(attr(fit,"certified"),TRUE)
  expect_identical(attr(fit,"unique"),TRUE)
  raw <- univariateML:::mlnorm_(c(-1,0,1))
  expect_identical(attr(raw$estimates,"certified"),TRUE)
  expect_identical(attr(raw$estimates,"unique"),TRUE)
  held <- mlnorm(c(1,2,3),mean=0,sd=1)
  expect_identical(attr(held,"certified"),TRUE)
  expect_identical(attr(held,"unique"),TRUE)
  fit <- mllaplace(c(-1,1))
  expect_identical(attr(fit,"unique"),FALSE)
  expect_output(print(fit),"Maximum is not unique")
  expect_output(summary(fit),"Maximum is not unique")
  for (fun in list(vcov,confint,bootstrapml))
    expect_error(fun(fit),"unique maximizer",class="univariateML_unsupported")
  selected <- model_select(c(-1,1),"laplace",return="all")
  expect_identical(selected$unique,FALSE)
  expect_identical(selected$certified,attr(fit,"certified"))
})

test_that("ties select existing witnesses and attach their complete set", {
  fit <- mlcauchy(c(-2,2),scale=1)
  witnesses <- attr(fit,"candidates")
  expect_identical(attr(fit,"certified"),FALSE)
  expect_identical(attr(fit,"unique"),TRUE)
  expect_identical(attr(fit,"fixed"),"scale")
  expect_identical(attr(logLik(fit),"df"),1L)
  chosen <- which.max(witnesses$loglik_lower)
  expect_identical(unname(coef(fit)),unname(unlist(witnesses[chosen,names(fit)])))
  expect_output(print(fit),"Global maximum is not certified")
  expect_output(summary(fit),"Global maximum is not certified")
  fit <- mllst(c(-100,-99,0,99,100),df=.5)
  expect_identical(attr(fit,"unique"),FALSE)
  expect_equal(nrow(attr(fit,"maximizers")),2L)
  expect_identical(unname(coef(fit)),unname(unlist(attr(fit,"maximizers")[1,names(fit)])))
})

test_that("stops carry classes, kinds, reasons and limit certification", {
  invalid <- tryCatch(mlnorm(numeric()),error=identity)
  expect_identical(class(invalid),c("univariateML_invalid","univariateML_stop","error","condition"))
  expect_identical(invalid$kind,"invalid")
  expect_identical(invalid$reason,"invalid-input")
  invalid <- tryCatch(mlnorm(c(0,1),sd=-1),error=identity)
  expect_s3_class(invalid,"univariateML_invalid")
  expect_identical(invalid$reason,"invalid-argument")
  unsupported <- tryCatch(mlgpd(c(1,2),mu=NULL),error=identity)
  expect_s3_class(unsupported,"univariateML_unsupported")
  nomle <- tryCatch(mlnorm(c(1,1)),error=identity)
  expect_s3_class(nomle,"univariateML_nomle")
  expect_identical(nomle$reason,"unbounded")
  limit <- tryCatch(mlnbinom(c(0,1)),error=identity)
  expect_s3_class(limit,"univariateML_limit")
  expect_type(limit$certified,"logical")
  budget <- tryCatch(mlskellam(c(-1e9,0,1e9),iterlim=1),error=identity)
  expect_s3_class(budget,"univariateML_budget")
  numerical <- tryCatch(mlpig(c(0,0,10),iterlim=1),error=identity)
  expect_s3_class(numerical,"univariateML_numerical")
  expect_true(numerical$reason %in% c("no-convergence","evaluation"))
})

test_that("accuracy and unresolved conditions retain their ordered classes and reasons", {
  for (entry in list(
      list(function() mlbinom(c(0,1,1),size=1,pi=0,zero="inflated",reltol=1e-20),"tolerance"),
      list(function() mlfoldnorm(c(1,1,1,sqrt(9+4*sqrt(6)))),"conditioning"))) {
    e <- tryCatch(entry[[1]](),error=identity)
    expect_identical(class(e),c(paste0("univariateML_",entry[[2]]),"univariateML_numerical","univariateML_stop","error","condition"))
    expect_identical(e$kind,entry[[2]])
    expect_identical(e$reason,entry[[2]])
  }
  e <- tryCatch(mlcmb(c(6000000,6000000),size=NULL,prob=.5),error=identity)
  expect_identical(class(e),c("univariateML_unresolved","univariateML_stop","error","condition"))
  expect_identical(e$reason,"unresolved")
})

test_that("uncertified limits describe the likelihood margin", {
  x <- c(-20,rep(-.1,10),rep(.1,10),20)
  e <- tryCatch(mlstd(x,mean=0),error=identity)
  expect_s3_class(e,"univariateML_limit")
  expect_identical(e$certified,FALSE)
  expect_match(conditionMessage(e)," No improvement above the likelihood margin was found\\.$")
})
