# Generate the internal R/Rcpp d/p/q/r layer during assembly, before
# compileAttributes. README coefficients are passed directly, in order;
# r.args and r.shift remain the resolver's responsibility.
source(file.path("scripts", "load_distributions.R"))
models <- load_distributions(dist_dir)
# Pending fitters still expose the internal d/p/q/r layer, without creating
# ml wrappers, fit metadata, or exported d/p/q/r functions.
for (folder in sort(list.dirs(dist_dir, full.names=TRUE, recursive=FALSE))) {
  if (file.exists(file.path(folder, "mle.hpp"))) next
  fm <- .umvl_read_front_matter(file.path(folder, "README.md"))
  if (identical(fm$front$stage, "dpqr")) {
    id <- basename(folder)
    models[[id]] <- .umvl_from_readme(file.path(folder, "README.md"), id)
  }
}
private_models <- dget("scripts/modifier_laws.R")
models <- c(models,private_models)
# All core APIs must use the same positional contract, including stats
# families. Catch metadata/signature drift before generating all-double calls.
for (m in models) {
  header <- paste(readLines(if(is.null(m$kernel_header)) file.path(dist_dir,m$id,"dpqr.hpp") else file.path(dist_dir,m$kernel_header), warn = FALSE), collapse = "\n")
  pn <- vapply(m$params, `[[`, "", "name")
  for (kind in c("d", "p", "q", "r")) {
    pattern <- paste0("inline\\s+double\\s+", kind, m$id, "\\s*\\(([^)]*)\\)")
    hit <- regmatches(header, regexec(pattern, header, perl = TRUE))[[1]]
    if (length(hit) != 2L) stop("codegen_dpqr: missing core signature: ", kind, m$id)
    args <- trimws(sub("=.*$", "", strsplit(hit[2], ",", fixed = TRUE)[[1]]))
    names <- sub("^.*[ &]", "", args)
    expected <- c(switch(kind, d="x", p="q", q="p", r="rng"), pn,
      switch(kind, d="log", p=, q=c("lower_tail", "log_p"), r=character()))
    types <- c(if (kind=="r") TRUE else startsWith(args[1], "double "),
               startsWith(args[seq_along(pn)+1L], "double "),
               if(kind!="r") startsWith(tail(args, if(kind=="d") 1L else 2L), "bool "))
    if (!identical(names, expected) || !all(types))
      stop("codegen_dpqr: nonuniform core signature: ", kind, m$id)
  }
}


# Check namespaces, including unexported objects, independently of what the
# codegen session happens to have attached. Never mask a default R function.
reserved <- unique(unlist(lapply(c("base", "stats", "utils", "graphics",
                                   "grDevices", "methods"), function(pkg)
  ls(asNamespace(pkg), all.names = TRUE))))
for (m in models) {
  generated <- if (startsWith(m$density, "core_")) paste0("core_", c("d", "p", "q"), m$id) else paste0(c("d", "p", "q", "r"), m$id)
  collision <- intersect(generated, reserved)
  if (length(collision)) stop("codegen_dpqr: reserved R name: ", paste(collision, collapse = ", "))
}

r_out <- c("# Generated by scripts/codegen_dpqr.R; do not edit.")
for (m in models) {
  pn <- vapply(m$params, `[[`, "", "name")
  coefficients <- pn
  # Library headers go first in the translation unit, before any Rcpp.h:
  # Rmath.h #defines names such as pnorm and log1mexp, and a library header
  # parsed after it would call renamed functions that were declared unrenamed.
  prelude <- c("// Generated by scripts/codegen_dpqr.R: library headers before Rcpp.h.",
            '#include "cppunivariate/special/special.hpp"',
            paste0('#include "cppunivariate/distributions/', if(is.null(m$kernel_header))paste0(m$id,'/dpqr.hpp') else m$kernel_header, '"'), "")
  cpp <- c("", "// ---- d/p/q/r entrypoints, generated by scripts/codegen_dpqr.R; do not edit.",
           '#include "dpqr.h"', '#include "rng_r.h"',
           if(m$id=="emg") '#include "rng_emg.h"',
           if (startsWith(m$density, "core_")) unlist(lapply(c("d", "p", "q"), function(k) c(paste0("#ifdef ", k, m$id), paste0("#undef ", k, m$id), "#endif"))))
  for (kind in if (startsWith(m$density, "core_")) c("d", "p", "q") else c("d", "p", "q", "r")) {
    fn <- paste0(if (startsWith(m$density, "core_")) "core_", kind, m$id)
    first <- switch(kind, d = "x", p = "q", q = "p", r = if ("n" %in% pn) "nn" else "n")
    flags <- switch(kind, d = "log = FALSE", p = , q = "lower.tail = TRUE, log.p = FALSE", r = character())
    r_formals <- paste(c(first, coefficients, flags), collapse = ", ")
    r_out <- c(r_out, paste0(fn, " <- function(", r_formals, ") {"))
    r_args <- c(first, pn, switch(kind, d="as.logical(log)[1L]",
                  p=, q=c("as.logical(lower.tail)[1L]", "as.logical(log.p)[1L]"), r=character()))
    if (kind == "r") {
      r_out <- c(r_out, paste0("  ", first, " <- univariateML_rng_length(", first, ")"),
        paste0("  if (!", first, " || any(lengths(list(", paste(pn, collapse=", "), ")) == 0L)) return(numeric())"),
        paste0("  ", pn, " <- rep_len(", pn, ", ", first, ")"))
    }
    if (startsWith(m$density, "core_")) {
      # R's Math2/3/4 shells copy attributes from the first longest numeric
      # argument. Retain names, dimensions and classes on the former stats API.
      r_out <- c(r_out,
        paste0("  values <- list(", paste(c(first, pn), collapse=", "), ")"),
        '  if (!all(vapply(values, function(v) typeof(v) %in% c("logical", "integer", "double") && !is.factor(v), logical(1))))',
        '    stop("Non-numeric argument to mathematical function", call. = FALSE)',
        paste0("  result <- ", fn, "_(", paste(r_args, collapse=", "), ")"),
        "  if (length(result)) attributes(result) <- attributes(values[[which.max(lengths(values))]])",
        "  result", "}", "")
    } else {
      r_out <- c(r_out, paste0("  ", fn, "_(", paste(r_args, collapse=", "), ")"), "}", "")
    }

    # Neutral C++ variable names avoid collisions with n, log, min, etc.
    vars <- paste0("v", seq_along(pn))
    cpp_flags <- switch(kind, d="bool log", p=, q=c("bool lower_tail", "bool log_p"), r=character())
    cpp_formals <- c(if (kind=="r") "int count" else "Rcpp::NumericVector value",
      paste0("Rcpp::NumericVector ", vars), cpp_flags)
    row_args <- paste0("a[", seq_along(pn), "]")
    call_args <- c(if(kind=="r") "rng" else "a[0]", row_args,
      switch(kind, d="log", p=, q=c("lower_tail", "log_p"), r=character()))
    cpp <- c(cpp, "// [[Rcpp::export]]", paste0("Rcpp::NumericVector ", fn, "_(", paste(cpp_formals, collapse=", "), ") {"),
      if(kind=="r") "  dist_impl::RRng rng;",
      paste0("  return dist_impl::dpqr_apply({", paste(c(if(kind=="r") "Rcpp::NumericVector(count)" else "value", vars), collapse=", "),
             "}, [&](const std::vector<double> &a) {"),
      # Some core samplers delegate straight to RNG primitives. Validate with
      # the family's density so invalid parameters cannot produce valid draws.
      if(kind=="r") paste0("    if (std::isnan(cppunivariate::distributions::d", m$id,
        "(0.0, ", paste(row_args, collapse=", "), ", false))) return R_NaN;"),
      paste0("    return (cppunivariate::distributions::", paste0(kind, m$id), ")(", paste(call_args, collapse=", "), ");"),
      paste0("  }", if(kind=="d" && m$support$type=="Z") ", true" else "", ");"), "}")
  }
  # Append to the family's adapter translation unit (src/dist_<id>.cpp, copied
  # by assemble_package.R just before this script) instead of writing a file of
  # its own: every translation unit re-parses Rcpp and Boost.Math, so one per
  # family roughly halves the package's compile time. Sources stay separate.
  target <- file.path(PKG_DIR, "src", paste0("dist_", m$id, ".cpp"))
  if (!file.exists(target)) {
    if (file.exists(file.path(dist_dir, m$id, "mle.hpp")))
      stop("codegen_dpqr: missing adapter translation unit: ", target)
    file.create(target)
  }
  writeLines(c(prelude, readLines(target, warn = FALSE), cpp), target)
}
writeLines(r_out, file.path(PKG_DIR, "R", "ml03_dpqr.R"))
