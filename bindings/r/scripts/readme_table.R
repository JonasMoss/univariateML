#!/usr/bin/env Rscript
# Rewrite the "Supported distributions" tables in README.Rmd and README.md
# from distributions/<id>/README.md (name, support, r.density). The tables
# sit between the markers below; run `just readme-table` after adding a
# distribution.

dossier_dir <- Sys.getenv(
  "UMVL_DOSSIER_DIR",
  "../../univariateML-cpp/include/cppunivariate/distributions"
)
source(file.path("scripts", "load_distributions.R"))
models <- load_distributions(dossier_dir)

start_marker <- "<!-- distributions: start (generated by scripts/readme_table.R) -->"
end_marker <- "<!-- distributions: end -->"

source_of <- function(density) {
  if (grepl("::", density, fixed = TRUE)) sub("::.*", "", density) else "univariateML"
}

md_table <- function(ms) {
  ms <- ms[order(tolower(vapply(ms, function(m) m$name, character(1))))]
  c("| Distribution | Function | d/p/q/r from |",
    "|---|---|---|",
    vapply(ms, function(m) {
      sprintf("| %s | `ml%s` | %s |", m$name, m$id, source_of(m$density))
    }, character(1)))
}

is_discrete <- vapply(models, function(m) identical(m$support$type, "Z"), logical(1))
block <- c(
  start_marker,
  "",
  sprintf("### Continuous distributions (%d)", sum(!is_discrete)),
  "",
  md_table(models[!is_discrete]),
  "",
  sprintf("### Discrete distributions (%d)", sum(is_discrete)),
  "",
  md_table(models[is_discrete]),
  "",
  end_marker
)

for (path in c("README.Rmd", "README.md")) {
  lines <- readLines(path)
  i <- match(start_marker, lines)
  j <- match(end_marker, lines)
  if (is.na(i) || is.na(j) || j < i) stop("markers not found in ", path)
  writeLines(c(lines[seq_len(i - 1L)], block, lines[-seq_len(j)]), path)
  message("wrote ", path)
}
