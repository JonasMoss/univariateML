"""Generate embind d/p/q/r from canonical dossiers; reject signature drift."""
from pathlib import Path
import re
import json
import argparse
import yaml

ROOT = Path(__file__).resolve().parents[2]
DOSSIERS = ROOT / 'univariateML-cpp/include/cppunivariate/distributions'


def golden_tolerance(expression, test_source):
    # The first branch in test_support.hpp is the declared wasm rule (or
    # double-width rule). Retain it when native #else branches repeat a name.
    constants = {}
    support = (ROOT / 'univariateML-cpp/tests/test_support.hpp').read_text()
    for name, value in re.findall(r'(?:constexpr|const) double (\w+)\s*=\s*([0-9.eE+-]+)\s*;', support + test_source):
        constants.setdefault(name, float(value))
    expression = expression.replace('mltest::', '')
    return float(eval(expression, {'__builtins__': {}}, constants))


def generate(selected=None):
    wrappers, exports, ids = [], [], []
    for folder in sorted(DOSSIERS.iterdir()):
        if not (folder / 'README.md').exists() or not (folder / 'mle.hpp').exists():
            continue
        model = yaml.safe_load((folder / 'README.md').read_text().split('---', 2)[1])
        family = model['id']
        if selected and family not in selected:
            continue
        ids.append(family)
        names = [p['name'] for p in model['params']]
        header = (folder / 'dpqr.hpp').read_text()
        wrappers.append(f'#include "cppunivariate/distributions/{family}/dpqr.hpp"\n')
        for kind in 'dpqr':
            match = re.search(r'inline\s+double\s+' + kind + family + r'\s*\(([^)]*)\)', header)
            if not match:
                raise ValueError(f'missing core signature: {kind}{family}')
            args = [a.split('=')[0].strip() for a in match[1].split(',')]
            expected = [dict(d='x', p='q', q='p', r='rng')[kind]] + names
            expected += dict(d=['log'], p=['lower_tail', 'log_p'], q=['lower_tail', 'log_p'], r=[])[kind]
            actual = [re.split(r'[ &]', a)[-1] for a in args]
            types = ['Rng' if kind == 'r' else 'double'] + ['double'] * len(names)
            types += ['bool'] * (len(expected) - len(types))
            if actual != expected or any(not a.startswith(t + ('&' if t == 'Rng' else ' ')) for a, t in zip(args, types)):
                # Templates use arbitrary RNG type identifiers, as in the R generator.
                if actual != expected or any(not a.startswith(t + ' ') for a, t in zip(args[1:], types[1:])) or (kind != 'r' and not args[0].startswith('double ')):
                    raise ValueError(f'nonuniform core signature: {kind}{family}: {args}')
            params = ','.join(f'p[{i}].as<double>()' for i in range(len(names)))
            if kind == 'r':
                body = f'''emscripten::val js_r{family}(unsigned n,emscripten::val p,unsigned seed) {{
  cppunivariate::distributions::StdRng<> rng(seed); std::vector<double> v(n);
  for(auto &z:v) z=std::isnan(cppunivariate::distributions::d{family}(0.0,{params},false)) ? NAN : cppunivariate::distributions::r{family}(rng,{params});
  return output(v);
}}'''
            else:
                flags = 'log' if kind == 'd' else 'lower,log'
                body = f'''emscripten::val js_{kind}{family}(emscripten::val x,emscripten::val p,bool lower,bool log) {{
  auto v=input(x); for(auto &z:v) z=cppunivariate::distributions::{kind}{family}(z,{params},{flags}); return output(v);
}}'''
            wrappers.append(body)
            exports.append(f'  emscripten::function("{kind}{family}",&js_{kind}{family});')
    return '\n'.join(wrappers), '\n'.join(exports), ids


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--families', help='comma-separated subset for size measurements')
    args = parser.parse_args()
    wrappers, exports, ids = generate(args.families.split(',') if args.families else None)
    target = ROOT / 'build/js/generated'
    target.mkdir(parents=True, exist_ok=True)
    (target / 'dpqr.hpp').write_text('// Generated by bindings/js/generate.py.\n' + wrappers + '\n')
    (target / 'exports.hpp').write_text(exports + '\n')
    (target / 'families.json').write_text(json.dumps(ids) + '\n')
    fits, fit_exports, fit_ids, fit_cases = [], [], [], []
    for family in ids:
        path = ROOT / f'bindings/common/distributions/{family}/fit.hpp'
        if not path.exists():
            continue
        fit_ids.append(family)
        metadata = yaml.safe_load((DOSSIERS / family / 'README.md').read_text().split('---', 2)[1])
        golden = json.loads((DOSSIERS / family / 'golden.json').read_text())
        coefficient_names = [p['name'] for p in metadata['params']]
        fit_args = golden.get('fit_args', {})
        # One calibrated policy for default golden fits across bindings. Native
        # and double/WASM captures (including reasons) are retained in the
        # TASK-149.1 report. Compare componentwise, with no additive unit scale.
        tol = golden_tolerance('mltest::kGolden_' + family, '')
        # Bhatt is owned by the concurrent all-free job. Preserve the existing
        # WASM coefficient/likelihood widths and additive scales for that family.
        deferred = family == 'bhatt'
        coefficient_tol = golden_tolerance('mltest::kBhattGoldenTol', '') if deferred else tol
        fit_cases.append(dict(id=family, g=golden,
            held={k:v for k,v in fit_args.items() if k in coefficient_names},
            control={k:v for k,v in fit_args.items() if k not in coefficient_names},
            holds=metadata.get('holds', []), limits=metadata.get('limits', []),
            tol=1e-10 if deferred else tol,
            tolerances={k:coefficient_tol for k in coefficient_names},
            tolerance_scales={k:int(deferred) for k in coefficient_names},
            ll_tol=1e-7 if deferred else tol, ll_scale=int(deferred)))

        header = path.read_text()
        signature = re.search(r'inline FitResult fit_' + family + r'\((.*?)\) \{', header, re.S)[1]
        metadata = yaml.safe_load((DOSSIERS / family / 'README.md').read_text().split('---', 2)[1])
        held_names, held_checks = [], []
        integer = 'cppunivariate::ispan x' in signature
        fit_cases[-1]['integer'] = integer
        call = ['cppunivariate::ispan{ix.data(),ix.size()}' if integer else 'cppunivariate::span{x.data(),x.size()}']
        for arg in signature.split(',')[1:]:
            declaration, default = arg.strip().split('=', 1)
            typ, name = declaration.strip().split()
            if typ == 'Held':
                key = name.removesuffix('_arg')
                if key in [p['name'] for p in metadata['params']]:
                    held_names.append(key)
                    local = 'held_' + str(len(held_names))
                    parameter = next(p for p in metadata['params'] if p['name'] == key)
                    positive = re.match(r'\(\s*0\s*,', parameter['domain']) is not None
                    diagnostic = f'Held `{key}` must be positive and finite.' if positive else f'Held `{key}` must not be NaN.'
                    held_checks.append('auto ' + local + '=held_arg(h,' + json.dumps(key) + '); if(' + local + '.supplied&&std::isnan(' + local + '.value)) return diagnostic(' + json.dumps(diagnostic) + '); ')
                    call.append(local)
                elif key in metadata['r'].get('control', {}):
                    call.append('held_arg(c,' + json.dumps(key) + ')')
                else:
                    raise ValueError(f'{family}: undocumented nullable control {key}')
            else:
                if name not in metadata['r'].get('control', {}):
                    raise ValueError(f'{family}: undocumented control {name}')
                adapter = (ROOT / f'bindings/r/distributions/{family}/adapter.cpp').read_text()
                formal = re.search(r'\b' + typ + r'\s+' + name + r'\s*=\s*([^,)]+)', adapter)
                if not formal or float(formal[1]) != float(default):
                    raise ValueError(f'{family}: R/shared default mismatch for {name}')
                value = 'control(c,' + json.dumps(name) + ',' + default.strip() + ')'
                call.append(f'static_cast<int>({value})' if typ == 'int' else value)
        if held_names != [p['name'] for p in metadata['params']]:
            raise ValueError(f'{family}: shared held coefficient order differs from dossier')
        support = metadata['support']
        # Preserve the pilot's observation check as a metadata-derived binding
        # boundary check. R's public wrappers already validate these data.
        validate = ''
        if integer:
            validate = 'std::vector<int> ix; ix.reserve(x.size()); for(double z:x) { if(!std::isfinite(z)||z!=std::floor(z)||z < -2147483648.0 || z > 2147483647.0) return diagnostic("Data must contain representable finite integers."); ix.push_back(static_cast<int>(z)); } '
        if support['lower'] == 0 and support['closed'][0] and str(support['upper']).lower() == 'inf':
            validate += 'for(double z:x) if(!std::isfinite(z)||z<0) return diagnostic("Data must be nonnegative and finite."); '
        else:
            validate += 'for(double z:x) if(!std::isfinite(z)) return diagnostic("Data must be finite."); '
        checks = ''.join(held_checks)
        fits.append(f'emscripten::val fit{family}(emscripten::val data,emscripten::val h,emscripten::val c) {{ auto x=input(data); {validate}{checks}return fit_output(umvl_binding::fit_{family}(' + ','.join(call) + ')); }')
        fit_exports.append(f'  emscripten::function("fit{family}",&fit{family});')
    (target / 'fit-cases.json').write_text(json.dumps(fit_cases) + '\n')
    (target / 'fit_includes.hpp').write_text(''.join(f'#include \"common/distributions/{family}/fit.hpp\"\n' for family in fit_ids))
    (target / 'fits.hpp').write_text('\n'.join(fits) + '\n')
    (target / 'fit_exports.hpp').write_text('\n'.join(fit_exports) + '\n')

    if not args.families:
        type_rows = []
        coefficient_registry = {}
        for family in fit_ids:
            model = yaml.safe_load((DOSSIERS / family / 'README.md').read_text().split('---', 2)[1])
            names = [p['name'] for p in model['params']]
            coefficient_registry[family] = names
            estimates = '; '.join(name + ': number' for name in names)
            params = ', '.join(name + ': number' for name in names)
            fit_header = (ROOT / f'bindings/common/distributions/{family}/fit.hpp').read_text()
            nullable = set(re.findall(r'Held (\w+) =', fit_header))
            controls = '; '.join(name + '?: number' + (' | null' if name in nullable else '') for name in model['r'].get('control', {}) if name not in names)
            control_type = '{' + controls + '}' if controls else 'Record<string, never>'
            type_rows.append(f'  {family}: Family<{{{estimates}}}, [{params}], {control_type}>;')
        (ROOT / 'bindings/js/family-types.d.ts').write_text(
            "// Generated by generate.py from canonical dossiers and shared fitters.\n"
            "import type {Family} from './index';\nexport interface GeneratedAPI {\n" +
            '\n'.join(type_rows) + '\n}\n')
        (ROOT / 'bindings/js/families.mjs').write_text('// Generated by generate.py from dossier front matter.\nexport const families = ' + json.dumps(ids) + ';\nexport const fitFamilies = ' + json.dumps(fit_ids) + ';\nexport const coefficients = ' + json.dumps(coefficient_registry) + ';\n')
    print(f'Validated and generated d/p/q/r for {len(ids)} families.')
