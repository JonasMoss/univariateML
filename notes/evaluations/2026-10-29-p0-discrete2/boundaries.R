# Small reproducible reference-versus-master boundary probes, run from repo root.
library(univariateML, lib.loc='/tmp/umvl-p0lib')
library(extraDistr)
probe <- function(label, expr) {cat('\n',label,':\n'); print(tryCatch(withCallingHandlers(expr, warning=function(w) invokeRestart('muffleWarning')),error=function(e) conditionMessage(e)))}
probe('CMP point mass is in reference', univariateML::dcmp(0:2,0,1))
probe('CMP geometric is in reference', univariateML::dcmp(0:2,.5,0))
probe('CMP fitter rejects held zero rate', mlcmp(c(0,0),lambda=0))
probe('CMP fitter at geometric face', mlcmp(c(0,0,0,0,1,1,2,3,8)))
probe('dlaplace reference real location', extraDistr::ddlaplace(0:1,.2,.4))
probe('dlaplace fitter real location', mldlaplace(c(0,1),location=.2))
probe('tpois reference singleton', extraDistr::dtpois(rep(2,2),3,1,2))
probe('tpois fitter singleton', mltpois(rep(2,2),a=1,b=2))
probe('tpois reference zero conditioning probability', extraDistr::dtpois(1:2,0,0,2))
probe('zipf fixed N unsupported', mlzipf(c(1,2),N=2))
probe('dunif fixed min unsupported', mldunif(c(1,2),min=1))
probe('tpois explicit NULL bounds', mltpois(c(1,2,3),a=NULL,b=NULL))
probe('tpois zero rate, zero included', extraDistr::dtpois(0:1,0,-1,1))
probe('dgamma zero reference rate', extraDistr::ddgamma(0:3,2,0))
probe('tpois infinite reference bounds', extraDistr::dtpois(0,1,-Inf,Inf))
probe('zipf all held', mlzipf(c(1,2),N=2,s=1))
probe('dunif all held', mldunif(c(1,2),min=1,max=2))
probe('yulesimon all held', mlyulesimon(c(1,2),rho=2))
probe('zeta all held', mlzeta(c(1,2),s=2))
