#!/usr/bin/env python3
"""Regenerate/check golden smoke-test manifest; no inference is inferred here."""
from pathlib import Path
import json
import re
import sys
import yaml
ROOT=Path(__file__).resolve().parents[2]
DIST=ROOT/'univariateML-cpp/include/cppunivariate/distributions'
REG=ROOT/'univariateML-cpp/include/cppunivariate/core/inference_numeric_generated.hpp'
OUT=ROOT/'univariateML-cpp/tests/inference_goldens.inc'
generated=re.findall(r'#include "\.\./distributions/([^/]+)/dpqr.hpp"',REG.read_text())
base='norm gamma beta pois exp geom lnorm logitnorm lgamma rayleigh binom'.split()
special='laplace gev gpd ged sged snorm sstd cmb cmp'.split()
families=sorted(set(base+generated+special))
rows=[]
for family in families:
    meta=yaml.safe_load((DIST/family/'README.md').read_text().split('---',2)[1])
    golden=json.loads((DIST/family/'golden.json').read_text())
    args=golden.get('fit_args') or {};p=meta['params'];names=[q['name'] for q in p]
    mask=sum(1<<i for i,q in enumerate(p) if q['name'] not in args or args[q['name']] is None)
    structural=sum(1<<i for i,q in enumerate(p) if q.get('kind','regular')!='regular' or (family=='dlaplace' and q['name']=='location'))
    names_cpp=','.join(json.dumps(name) for name in names)
    rows.append(f'    {{{json.dumps(family)},{{{names_cpp}}},{mask}u,{structural}u}},')
result=['// Generated by dev/validation/inference-golden-fixtures.py; do not edit.',
'''  struct InferenceFixture {std::string id;std::vector<std::string> names;unsigned mask,structural;};
  const std::vector<InferenceFixture> fixtures={''',*rows,'''  };
  for(const auto& fixture:fixtures) {
    CAPTURE(fixture.id);
    const auto golden=mltest::load_distribution_golden(fixture.id);
    std::array<double,cppunivariate::inference_max_parameters> values{};
    for(std::size_t i=0;i<fixture.names.size();++i) values[i]=golden.estimates.at(fixture.names[i]);
    const auto info=cppunivariate::family_inference(mltest::as_span(golden.data),fixture.id,values,fixture.mask);
    if(fixture.mask & fixture.structural) {
      CHECK((info.status==cppunivariate::InferenceStatus::InvalidSubset || info.status==cppunivariate::InferenceStatus::RegimeUnavailable));
      continue;
    }
    if(info.status!=cppunivariate::InferenceStatus::Ok) {
      CHECK((info.status==cppunivariate::InferenceStatus::BoundaryOrLimit || info.status==cppunivariate::InferenceStatus::RegimeUnavailable || info.status==cppunivariate::InferenceStatus::Singular));
      CHECK(!info.validity_conditions.empty());
      continue;
    }
    for(std::size_t i=0;i<info.dimension;++i) {
      CHECK(std::isfinite(info.score[i]));
      for(std::size_t j=0;j<info.dimension;++j) {
        CHECK(std::isfinite(info.observed[i*info.dimension+j]));
        CHECK(info.observed[i*info.dimension+j]==info.observed[j*info.dimension+i]);
      }
    }
    const auto cov=cppunivariate::inference_covariance(info,cppunivariate::CovarianceKind::Observed);
    CHECK((cov.status==cppunivariate::InferenceStatus::Ok || cov.status==cppunivariate::InferenceStatus::Singular || cov.status==cppunivariate::InferenceStatus::IllConditioned || cov.status==cppunivariate::InferenceStatus::Indefinite));
  }
''','']
rendered='\n'.join(result)
if '--write' in sys.argv:
    OUT.write_text(rendered);print('wrote',len(families),'golden fixtures')
else:
    if not OUT.exists() or OUT.read_text()!=rendered: raise SystemExit('golden fixture manifest is stale')
    print('golden fixture manifest matches',len(families),'families')
