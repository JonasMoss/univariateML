#!/usr/bin/env python3
"""Generate/check the experimental fixed-support family dispatch registry.

The explicit allowlist is a review boundary: metadata cannot enable a family
by itself. This is separate from R codegen. Run with --write to regenerate the
header and without arguments to compare it byte-for-byte. It is not a validation
of numerical derivatives or inference calibration.
"""
from pathlib import Path
import sys
import yaml

ROOT=Path(__file__).resolve().parents[2]
DIST=ROOT/'univariateML-cpp/include/cppunivariate/distributions'
OUTPUT=ROOT/'univariateML-cpp/include/cppunivariate/core/inference_numeric_generated.hpp'
FAMILIES='''bbinom betapr bhatt bnbinom burr cauchy dgamma dlaplace dnorm dweibull emg fatigue foldnorm fpareto frechet gb2 genbeta gompertz gumbel hcauchy hnorm ht invburr invexp invgamma invgauss invparalogis invpareto invtrgamma invweibull kumar lgser llogis logis lomax lst naka nbinom nsbeta paralogis pareto pareto2 pareto3 pareto4 power sgomp skellam slash sn std trgamma weibull yulesimon zeta zib zinb zip zipf zmgeom zmlogarithmic zmnbinom zmpois ztbinom ztgeom ztnbinom ztpois'''.split()
# These numbers are structural or require an identifiable finite support.
MIN_SIZE={'bbinom':0,'zib':0,'ztbinom':1,'zipf':1}
result=['// Generated by dev/validation/inference-family-registry.py; do not edit.',
        '// These entries still require independent numerical and estimator validation.',
        '#pragma once','#include "inference_numeric.hpp"']
result += [f'#include "../distributions/{f}/dpqr.hpp"' for f in FAMILIES]
result += ['namespace cppunivariate {',
           'template<class Emit=inference_detail::Discard>',
           'inline InferenceResult generated_family_inference(span data,const std::string& family,',
           '    const std::array<double,inference_max_parameters>& value,unsigned mask,Emit emit={}) {']
for family in FAMILIES:
    text=(DIST/family/'README.md').read_text()
    meta=yaml.safe_load(text.split('---',2)[1]); params=meta['params']; n=len(params)
    if not any(scope['available'] for scope in meta.get('inference_numeric',[])):
        raise ValueError((family,'no eligible metadata scope'))
    kinds=[]; structural=[]
    for i,p in enumerate(params):
        name=p['name'];domain=str(p['domain']).replace(' ','');kind=p.get('kind','regular')
        if kind in ('design','threshold','endpoint') or (family=='dlaplace' and name=='location'):
            kinds.append(('Real',0));structural.append(i)
        elif domain in ('(-inf,inf)','(-inf,inf]'):
            kinds.append(('Real',0))
        elif domain in ('(0,1)','(0,1]','[0,1]','[0,1)'):
            kinds.append(('UnitInterval',0))
        elif domain in ('(0,inf)','[0,inf)'):
            kinds.append(('Positive',0))
        elif domain in ('(1,inf)','[1,inf)'):
            kinds.append(('LowerBounded',1))
        elif domain=='(2,inf)': kinds.append(('LowerBounded',2))
        else: raise ValueError((family,name,domain))
    mask_allowed=sum(1<<i for i in range(n) if i not in structural)
    result += [f'  if(family=="{family}") {{',f'    constexpr std::size_t n={n};',
      '    if(mask >= (1u<<n)) {InferenceResult r;r.status=InferenceStatus::InvalidSubset;return r;}',
      f'    if(mask & ~{mask_allowed}u) {{InferenceResult r;r.status=InferenceStatus::InvalidSubset;r.validity_conditions="design, threshold and endpoint coefficients must be held";return r;}}',
      '    std::array<NumericParameter,inference_max_parameters> p{};']
    for i,(param,(kind,lower)) in enumerate(zip(params,kinds)):
        domain=str(param['domain']).replace(' ','')
        result += [f'    p[{i}]={{"{param["name"]}",value[{i}],NumericCoordinate::{kind},{lower}}};']
        if i in structural:
            check=f'!std::isfinite(value[{i}])'
            if domain=='(0,inf)':
                check+=f' || value[{i}]<=0'
            elif domain=='[0,inf)':
                check+=f' || value[{i}]<0'
            if family=='dlaplace': check+=f' || value[{i}]!=std::floor(value[{i}])'
            if family in MIN_SIZE:
                check+=f' || value[{i}]<{MIN_SIZE[family]} || value[{i}]!=std::floor(value[{i}])'
        elif kind=='Real': check=f'!std::isfinite(value[{i}])'
        elif kind=='Positive': check=f'!(std::isfinite(value[{i}]) && value[{i}]>0)'
        elif kind=='UnitInterval': check=f'!(std::isfinite(value[{i}]) && value[{i}]>0 && value[{i}]<1)'
        else: check=f'!(std::isfinite(value[{i}]) && value[{i}]>{lower})'
        if family=='foldnorm' and param['name']=='mu':
            check=f'!(std::isfinite(value[{i}]) && (value[{i}]>0 || (value[{i}]==0 && !(mask & 1u))))'
        if family=='bhatt' and param['name']=='a':
            check=f'!(std::isfinite(value[{i}]) && (value[{i}]>0 || (value[{i}]==0 && !(mask & (1u<<{i})))))'
        held_zero=(family in ('zmnbinom','ztnbinom','nbinom','zinb') and param['name']=='size') or (family=='zmpois' and param['name']=='lambda') or (family=='sgomp' and param['name']=='eta')
        held_unit=((family in ('zib','nbinom','zinb','ztnbinom','zmnbinom','zmgeom') and param['name']=='prob') or
                   (family=='zmlogarithmic' and param['name']=='prob'))
        if held_zero:
            check=f'!(std::isfinite(value[{i}]) && (value[{i}]>0 || (value[{i}]==0 && !(mask & (1u<<{i})))))'
        if held_unit:
            allowed_boundary='value['+str(i)+']==1' if family!='zmlogarithmic' else 'value['+str(i)+']==0'
            if family=='zib': allowed_boundary=f'(value[{i}]==0 || value[{i}]==1)'
            check=f'!(std::isfinite(value[{i}]) && ((value[{i}]>0 && value[{i}]<1) || ({allowed_boundary} && !(mask & (1u<<{i})))))'
        boundary_mixture=(family in ('zinb','zip','zib') and param['name']=='pi') or (family in ('zmgeom','zmlogarithmic','zmpois') and param['name']=='p0')
        if boundary_mixture:
            check=f'!(std::isfinite(value[{i}]) && ((value[{i}]>0 && value[{i}]<1) || ((value[{i}]==0 || value[{i}]==1) && !(mask & (1u<<{i})))))'
        result += [f'    if({check}) {{InferenceResult r;r.status=InferenceStatus::BoundaryOrLimit;r.validity_conditions="outside the recorded interior scope";return r;}}']
    if family in ('nbinom','zinb'):
        result += ['    if((value[0]==0 || value[1]==1) && mask) {return inference_numeric_detail::singular_integer_support(data,0,0,"known boundary gives a point mass");}']
    if family=='zib':
        result += ['    if(value[1]==0 && mask) {return inference_numeric_detail::singular_integer_support(data,0,0,"known zero probability gives a point mass");}']
    if family=='ztnbinom':
        result += ['    if(value[1]==1 && mask) {return inference_numeric_detail::singular_integer_support(data,1,1,"known unit probability gives a point mass");}']
    if family=='zmnbinom':
        result += ['    if(value[1]==1 && (mask & 1u)) {return inference_numeric_detail::singular_integer_support(data,value[2]==0?1:0,value[2]==1?0:1,"size is unidentified when probability is one");}']
    if family in ('zinb','zip','zib','zmgeom','zmlogarithmic','zmpois'):
        boundary_name='pi' if family in ('zinb','zip','zib') else 'p0'
        i=next(i for i,p in enumerate(params) if p['name']==boundary_name)
        result += [f'    if(value[{i}]==1 && mask) {{return inference_numeric_detail::singular_integer_support(data,0,0,"held boundary yields a point mass");}}']
    if family in ('bbinom','zib'):
        result += ['    if(value[0]==0 && mask) {return inference_numeric_detail::singular_integer_support(data,0,0,"size zero is a point mass");}',
                   '    if(value[0]==1 && (mask & 6u)==6u) {return inference_numeric_detail::singular_integer_support(data,0,1,"size one identifies only one combination of the two free coefficients");}']
    if family in ('ztbinom','zipf'):
        result += ['    if(value[0]==1 && mask) {return inference_numeric_detail::singular_integer_support(data,1,1,"size one is a point mass");}']
    if family=='lst':
        result += ['    if((mask & 5u)==5u && !(value[2]>1)) {InferenceResult r;r.status=InferenceStatus::BoundaryOrLimit;r.validity_conditions="free df and location require df > 1";return r;}',
                   '    if((mask & 5u)==5u) {p[2].coordinate=NumericCoordinate::LowerBounded;p[2].lower=1;}']
    if family=='sn':
        result += ['    if(value[2]==0 && (mask & 5u)==5u) {return inference_numeric_detail::singular_real_support(data,"shape and location information is singular at alpha = 0");}']
    if family=='nsbeta':
        result += ['    if(!(value[2]<value[3])) {InferenceResult r;r.status=InferenceStatus::InvalidParameter;return r;}']
    args=','.join(f'a[{i}]' for i in range(n))
    result += [f'    const auto density=[](double x,const auto& a) {{return distributions::d{family}(x,{args},true);}};',
      f'    const NumericEligibility eligibility{{InferenceStatus::Ok,{mask_allowed}u,"finite interior scope; structural coefficients held"}};',
      '    return numeric_inference_checked(data,p,n,mask,eligibility,density,emit);',
      '  }']
result += ['  InferenceResult r;r.status=InferenceStatus::FamilyUnavailable;',
           '  r.validity_conditions="family regime has not been classified and implemented";return r;',
           '}','} // namespace cppunivariate','']
rendered='\n'.join(result)
if '--write' in sys.argv:
    OUTPUT.write_text(rendered)
    print('wrote',OUTPUT.relative_to(ROOT))
else:
    if not OUTPUT.exists() or OUTPUT.read_text()!=rendered:
        raise SystemExit('numeric inference registry is stale; regenerate with --write')
    print('numeric inference registry matches',len(FAMILIES),'reviewed entries')
