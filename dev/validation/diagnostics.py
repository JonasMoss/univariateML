#!/usr/bin/env python3
"""Generate the TASK-132 standalone audit using the shared fit call routing.

No fitter is mocked: validation-only routes extracted from binding headers
observe core results before binding diagnostics and bypass binding guards.
Integer spans cannot represent fractional/NaN/Inf input; R checks conversion.
Run: python3 dev/validation/diagnostics.py --generate build/diagnostics
Then compile generated audit.cpp with the core and Boost include directories.
Copy it to dev/validation/diagnostics-audit.cpp to update the dev-tier test.
"""
import argparse, json, pathlib, re
import yaml
ROOT = pathlib.Path(__file__).resolve().parents[2]
DISTS = ROOT/'univariateML-cpp/include/cppunivariate/distributions'

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--generate',type=pathlib.Path,required=True)
    out=ap.parse_args().generate.resolve(); out.mkdir(parents=True,exist_ok=True)
    observer=r'''#pragma once
#include <cmath>
#include <iostream>
#include <string>
#include <type_traits>
#include <utility>
#include <vector>
namespace audit {
inline std::string family, input, held;
inline bool invalid=false, seen=false;
inline int defects=0;
template<class T,class=void> struct status {static int get(const T&){return -1;}};
template<class T> struct status<T,std::void_t<decltype(std::declval<T>().status)>> {static int get(const T&r){return static_cast<int>(r.status);}};
struct Value {std::string name;double value,low,high;bool closed_low,closed_high;};
template<class T> void observe(const T&r,std::initializer_list<Value> values) {
 if(seen)return;seen=true;
 const int s=status<T>::get(r);bool finite=std::isfinite(r.logLik),domain=true;
 for(const auto&v:values){finite=finite&&std::isfinite(v.value);domain=domain&&!std::isnan(v.value)&&(v.closed_low?v.value>=v.low:v.value>v.low)&&(v.closed_high?v.value<=v.high:v.value<v.high);}
 const bool defect=(s==0||s==-1)&&(!std::isfinite(r.logLik)||!domain||invalid);
 defects+=defect;
 std::cout<<family<<','<<held<<','<<input<<','<<s<<','<<finite<<','<<domain<<','<<invalid<<','<<defect<<','<<r.logLik;
 for(const auto&v:values)std::cout<<','<<v.name<<'='<<v.value;
 std::cout<<'\n';
}
}
'''
    (out/'observer.hpp').write_text(observer)
    src=[observer.replace('#pragma once\n','// Generated by dev/validation/diagnostics.py; do not edit.\n'), '#include <algorithm>\n#include <limits>\n#include <sstream>', 'namespace audit {struct Held {bool supplied=false;double value=NAN;std::size_t length=1;};}']
    src.append('template<class... T> std::string binding_message(std::string s,const T&...){return s;}')
    routes=[]
    blocks=[]
    for folder in sorted(DISTS.iterdir()):
        if not (folder/'golden.json').exists():continue
        model=yaml.safe_load((folder/'README.md').read_text().split('---')[1]); id=model['id']
        golden=json.loads((folder/'golden.json').read_text()); params=model['params']; names=[p['name'] for p in params]
        header=ROOT/'bindings/common/distributions'/id/'fit.hpp'; text=header.read_text()
        signature=text.split('inline FitResult fit_'+id+'(',1)[1].split(') {',1)[0]
        actual=[n.removesuffix('_arg') for n in re.findall(r'\bHeld\s+(\w+)',signature)][:len(names)]
        if actual!=names:raise RuntimeError((id,'coefficient order',actual,names))
        # Locate declarations holding the final core result (including conditional routes).
        pattern=r'(?:(?:const\s+)?auto|cppunivariate::\w+Result)\s+(\w+)\s*=\s*([^;]+);'
        hits=[m for m in re.finditer(pattern,text) if 'cppunivariate::' in m[2] and ('mle' in m[2] or 'fit_cauchy' in m[2] or 'fit_gumbel' in m[2])]
        for hit in reversed(hits):
            var=hit[1]
            if var=='profile':continue
            values=[]
            fields_by_name={}
            for p in params:
                entries=re.findall(r'\{"'+re.escape(p['name'])+r'",([^}\n]+)\}',text)
                if not entries:entries=re.findall(r'emplace_back\(\"'+re.escape(p['name'])+r'\",([^\)]+)\)',text)
                fields=[f for entry in entries for f in re.findall(r'\b'+var+r'\.(\w+)',entry)]
                if fields:fields_by_name[p['name']]=var+'.'+fields[-1]
                elif entries:fields_by_name[p['name']]=entries[-1].strip()
                else:raise RuntimeError((id,p['name'],'missing coefficient mapping'))
            if id=='cmp':fields_by_name['lambda']=f'std::exp({var}.eta)'
            if id=='tpois':
                fields_by_name['a']='(a.supplied?a.value:(x.empty()?NAN:double(*std::min_element(x.begin(),x.end()))-1))'
                fields_by_name['b']='(b.supplied?b.value:(x.empty()?NAN:double(*std::max_element(x.begin(),x.end()))))'
            for p in params:
                name=p['name'];val=fields_by_name[name]
                dom=p['domain'].strip(); lo,hi=dom[1:-1].split(',')
                def bound(s):
                    s=s.strip()
                    for n,expr in fields_by_name.items():s=re.sub(r'\b'+re.escape(n)+r'\b','('+expr+')',s)
                    return {'inf':'INFINITY','-inf':'-INFINITY'}.get(s,s)
                values.append('{'+json.dumps(name)+','+val+','+bound(lo)+','+bound(hi)+','+str(dom[0]=='[').lower()+','+str(dom[-1]==']').lower()+'}')
            text=text[:hit.end()]+f' audit::observe({var}, {{{",".join(values)}}});'+text[hit.end():]
        # cmb uses an assignment after the size-held branch.
        if id=='cmb':
            text=text.replace('switch (res.status)', 'audit::observe(res, {{"size",trials,0,INFINITY,true,false},{"prob",res.prob,0,1,true,true},{"nu",res.nu,-INFINITY,INFINITY,false,false}});\n  switch (res.status)')
        if not hits and id!='cmb':raise RuntimeError(id)
        includes=re.findall(r'^#include [<"](?:cppunivariate/[^"\n]+|[^"\n]+)[>"]$',text,re.M)
        src.extend(i for i in includes if '../../' not in i and 'fit.hpp' not in i)
        start=text.index('inline FitResult fit_')
        end=text.index(' audit::observe(') if id!='cmb' else text.index('audit::observe(res,')
        end=text.index(';',end)+1
        route=text[start:end]
        if id=='tbinom':
            route=route.replace('double(*std::min_element(x.begin(),x.end()))','(x.empty()?0.0:double(*std::min_element(x.begin(),x.end())))').replace('double(*std::max_element(x.begin(),x.end()))','(x.empty()?0.0:double(*std::max_element(x.begin(),x.end())))')
        route=route.replace('inline FitResult fit_', 'inline void route_').replace('Held','audit::Held')
        route=re.sub(r'^  const auto fail = .*\n','',route,flags=re.M)
        # Remove binding guards from this validation-only route, so bad data
        # reaches the actual core. Parse quoted messages including semicolons.
        pattern=re.compile(r'return (?:fail|failure)\(')
        while (match:=pattern.search(route)):
            pos=match.end();depth=1;quoted=False;escape=False
            while depth:
                ch=route[pos];pos+=1
                if escape:escape=False;continue
                if ch=='\\' and quoted:escape=True;continue
                if ch=='"':quoted=not quoted
                if not quoted:
                    if ch=='(':depth+=1
                    if ch==')':depth-=1
            assert route[pos]==';'
            route=route[:match.start()]+'(void)0'+route[pos:]
        routes.append(route+'\n}\n')
        integer='cppunivariate::ispan' in text.split('{',1)[0] or bool(re.search(r'fit_'+id+r'\(cppunivariate::ispan',text))
        kind='int' if integer else 'double'; sp='ispan' if integer else 'span'
        g=golden['estimates']; vals=[g.get(n,p.get('simulate')) for n,p in zip(names,params)]
        # Support bounds use held golden coefficients. Free endpoints are allowed to move.
        env=dict(zip(names,vals));env.update(inf=float('inf'), Inf=float('inf'), max=max, min=min, floor=__import__('math').floor, ceil=__import__('math').ceil)
        def support(s):
            try:return float(eval(str(s),{'__builtins__':{}},env))
            except (NameError,TypeError,SyntaxError,ValueError):return None
        low=support(model['support']['lower']); high=support(model['support']['upper'])
        typical=golden['data'][0]
        cases=[('empty',[]),('one',[typical]),('constant',[typical]*4),('zero',[0]*4),('negative',[-1,-2,-3]),('unit-boundary',[0,1,0,1])]
        if low is not None and abs(low)!=float('inf'):
            cases.extend([('lower',[low]*4),('below',[low-1]*4)])
        if high is not None and abs(high)!=float('inf'):
            cases.extend([('upper',[high]*4),('above',[high+1]*4)])
        if model['support']['type']=='integer' and not integer:cases.append(('fractional',[.5,1.5]))
        if not integer:cases.extend([('nan',[float('nan'),typical]),('posinf',[float('inf'),typical]),('neginf',[-float('inf'),typical])])
        def cpp(v):
            if isinstance(v,str):return {'Inf':'INFINITY','-Inf':'-INFINITY'}.get(v,v)
            return 'NAN' if v!=v else ('INFINITY' if v==float('inf') else '-INFINITY' if v==-float('inf') else repr(v))
        b=['{',f'audit::family="{id}";', f'for(unsigned mask=0;mask<{1<<len(params)};++mask){{']
        excluded=[]
        for mask in range(1<<len(params)):
            held=[n for i,n in enumerate(names) if mask>>i&1]
            if any(set(h.get('held',[]))==set(held) for h in model.get('holds',[])):excluded.append(mask)
        if excluded:b.append('if('+ '||'.join(f'mask=={m}' for m in excluded)+')continue;')
        b.append('audit::held="";')
        for i,n in enumerate(names):b.append(f'if(mask&{1<<i})audit::held+="{n}+";')
        args=','.join(f'audit::Held{{bool(mask&{1<<i}),mask&{1<<i}?{cpp(vals[i])}:NAN}}' for i in range(len(params)))
        b.append(f'std::vector<std::pair<std::string,std::vector<{kind}>>> cases={{')
        for label,data in cases:
            if integer:data=[int(v) for v in data]
            b.append('{'+json.dumps(label)+', {'+','.join(cpp(v) for v in data)+'}},')
        b.extend(['};','for(const auto& item:cases){const auto& x=item.second;', 'audit::input=item.first;audit::seen=false;audit::invalid=x.empty();'])
        b.append('for(double v:x){audit::invalid=audit::invalid||!std::isfinite(v);')
        if model['support']['type']=='integer':b.append('audit::invalid=audit::invalid||(v!=std::floor(v));')
        for bound_value,bound_expr,closed,lower in [(low,str(model['support']['lower']),model['support']['closed'][0],True),(high,str(model['support']['upper']),model['support']['closed'][1],False)]:
            if bound_value is None or abs(bound_value)==float('inf'):continue
            relevant=[i for i,n in enumerate(names) if re.search(r'\b'+re.escape(n)+r'\b',bound_expr)]
            cond=' && '.join(f'(mask&{1<<i})' for i in relevant) or 'true'
            op=('<' if closed else '<=') if lower else ('>' if closed else '>=')
            b.append(f'if({cond})audit::invalid=audit::invalid||(v{op}{cpp(bound_value)});')
        b.extend(['}',f'route_{id}(cppunivariate::{sp}{{x.data(),x.size()}},{args});', 'if(!audit::seen){std::cerr<<audit::family<<": missing core observation\\n";return 2;}','}}}'])
        blocks.extend(b)
    src.extend(routes)
    src.extend(['int main(){std::cout<<"family,held,input,status,finite,domain,invalid,defect,logLik,estimates\\n";']+blocks+['return audit::defects?1:0;}'])
    (out/'audit.cpp').write_text('\n'.join(src)+'\n')
if __name__=='__main__':main()
