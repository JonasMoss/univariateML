# Probe fits at the edges of each family; see dev/research/ml-behaviour.tex.
# Run from the repo root after `just regen`: Rscript dev/research/ml-behaviour-probe.R
suppressMessages(pkgload::load_all("univariateML-r", quiet = TRUE, compile = FALSE))
fit <- function(f, x) tryCatch({ r <- f(x); paste(paste(names(r), signif(unclass(r), 5), sep = "=", collapse = " "), " logLik=", signif(attr(r, "logLik"), 7)) }, error = function(e) paste("ERROR:", conditionMessage(e)))
show <- function(label, f, x, ref = NULL) { cat(sprintf("%-46s %s\n", label, fit(f, x))); if (!is.null(ref)) cat(sprintf("%-46s %s\n", "   (limit model)", fit(ref, x))) }
set.seed(1)
cat("== t-family: normal data, nu -> Inf? ==\n")
for (n in c(30, 200)) { x <- rnorm(n); show(paste0("mlstd   normal n=", n), mlstd, x, mlnorm) }
x <- runif(200, -1, 1); show("mlstd   uniform n=200", mlstd, x, mlnorm)
cat("== GED: uniform data, nu -> Inf? ==\n")
x <- runif(200, -1, 1); show("mlged   uniform n=200", mlged, x, mlunif)
cat("== skew families: exponential data, xi -> Inf? ==\n")
x <- rexp(200); show("mlsnorm exp n=200", mlsnorm, x)
show("mlsstd  normal n=200", mlsstd, rnorm(200), mlsnorm)
show("mlsged  uniform n=200", mlsged, runif(200))
cat("== invburr: all x <= 1 -> power(1, a)? ==\n")
x <- runif(200)^(1/2); show("mlinvburr all<=1", mlinvburr, x, mlpower)
cat("== burr: all x >= 1 (control) and mostly >= 1 ==\n")
x <- 1 + rexp(200); show("mlburr all>=1", mlburr, x)
x <- c(1 + rexp(199), 0.99); show("mlburr one obs 0.99", mlburr, x, mlpareto)
cat("== nakagami: shape < 1/2 data ==\n")
x <- sqrt(rgamma(200, 0.3, 1)); show("mlnaka m_true=0.3", mlnaka, x)
cat("== zip: zero-deflated data ==\n")
x <- rpois(200, 3); x <- x[!(x == 0 & runif(200) < 0.9)]; show("mlzip few zeros", mlzip, x, mlpois)
cat("== invgauss: Levy-like data (mean -> Inf limit) ==\n")
x <- 1 / rnorm(200)^2; show("mlinvgauss levy n=200", mlinvgauss, x)
cat("== kumar / betapr / beta near limits ==\n")
show("mlkumar beta(0.05,0.05)", mlkumar, pmin(pmax(rbeta(200, .05, .05), 1e-12), 1 - 1e-12))
show("mlbetapr exp data", mlbetapr, rexp(200))
cat("== gompertz / lomax / nbinom controls ==\n")
show("mlgompertz exp data", mlgompertz, rexp(200))
show("mllomax exp data", mllomax, rexp(200))
show("mlnbinom pois data", mlnbinom, rpois(200, 4))
