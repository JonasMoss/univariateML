"""50-digit direct-likelihood maximization in log coefficient (golden section).
Run from repository root. Writes JSON evidence and standalone C++ fixtures.
No closed-form coefficient, derivative, or fitter is used by the optimizer.
"""
import json, math, random
from pathlib import Path
import mpmath as mp
mp.mp.dps = 50
OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[3]
rng = random.Random(14223)

def maximize(f):
    a,b=mp.mpf(-20),mp.mpf(20)
    q=(mp.sqrt(5)-1)/2
    c,d=b-q*(b-a),a+q*(b-a)
    fc,fd=f(c),f(d)
    for _ in range(280):
        if fc>fd:
            b,d,fd=d,c,fc;c=b-q*(b-a);fc=f(c)
        else:
            a,c,fc=c,d,fd;d=a+q*(b-a);fd=f(d)
    z=(a+b)/2
    assert f(z-mp.mpf('1e-15')) < f(z) and f(z+mp.mpf('1e-15')) < f(z)
    return z,f(z)

cases=[]
for family in ['exp','weibull','rayleigh','pareto','lomax']:
    for scale in [1.,1e-200,1e200]:
        for label,n,nc in [('0pct',10,0),('30pct',10,3),('90pct',10,9),('ties',10,3),('single',1,0)]:
            values=[scale*(1.25 if label=='ties' else 1+rng.random()*3) for _ in range(n)]
            flags=[i>=nc for i in range(n)]
            held=1.7 if family=='weibull' else scale if family=='pareto' else 1/scale if family=='lomax' else 1.
            xx=list(map(mp.mpf,values)); h=mp.mpf(held); s=mp.mpf(scale)
            def ll(z):
                coef=mp.exp(z)*(1/s if family=='exp' else s if family in ['weibull','rayleigh'] else 1)
                ans=mp.mpf(0)
                for x,exact in zip(xx,flags):
                    if family=='exp':
                        ans-=coef*x
                        if exact:ans+=mp.log(coef)
                    elif family=='weibull':
                        ans-=(x/coef)**h
                        if exact:ans+=mp.log(h/coef)+(h-1)*mp.log(x/coef)
                    elif family=='rayleigh':
                        ans-=x*x/(2*coef*coef)
                        if exact:ans+=mp.log(x)-2*mp.log(coef)
                    elif family=='pareto':
                        ans-=coef*mp.log(x/h)
                        if exact:ans+=mp.log(coef)-mp.log(x)
                    else:
                        t=mp.log1p(h*x);ans-=coef*t
                        if exact:ans+=mp.log(coef*h)-t
                return ans
            z,loglik=maximize(ll)
            coef=mp.exp(z)*(1/s if family=='exp' else s if family in ['weibull','rayleigh'] else 1)
            cases.append(dict(family=family,label=label,scale=scale,held=held,lower=values,exact=flags,coefficient=str(coef),logLik=str(loglik)))
(OUT/'oracle.json').write_text(json.dumps(dict(dps=50,seed=14223,method='golden-section direct censored log likelihood in log coefficient',cases=cases),indent=2)+'\n')
lines=['// Generated by dev/research/evaluations/2026-11-11-cens-easy-data/oracle.py', '#pragma once', '#include <vector>', '#include <string>', 'namespace censored_reference {', 'struct Case { const char* family; const char* label; double held, coefficient, logLik; std::vector<double> lower; std::vector<int> exact; };', 'inline std::vector<Case> cases() { return {']
for c in cases:
    lines.append('{"%s","%s",%r,%s,%s,{%s},{%s}},'%(c['family'],c['label'],c['held'],repr(float(c['coefficient'])),repr(float(c['logLik'])),','.join(map(repr,c['lower'])),','.join(str(int(x)) for x in c['exact'])))
lines+=['}; }', '} // namespace censored_reference']
(ROOT/'univariateML-cpp/tests/censored_reference.hpp').write_text('\n'.join(lines)+'\n')
print(f'{len(cases)} direct-likelihood maxima; 50 digits; seed 14223')
