"""Weibull right censoring with shape free (scale free or held): direct
maximisation of the censored log likelihood by nested golden sections in
log coefficients at 30 digits. Uses no score, profile formula or fitter.
Run from the repository root; writes oracle_weibull_free.json and
univariateML-cpp/tests/censored_reference_weibull_free.hpp.
"""
import json, random
from pathlib import Path
import mpmath as mp
mp.mp.dps = 30
OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[3]
rng = random.Random(20261111)

def golden(f, a, b, iters=130):
    a, b = mp.mpf(a), mp.mpf(b); q = (mp.sqrt(5) - 1) / 2
    c, d = b - q*(b - a), a + q*(b - a); fc, fd = f(c), f(d)
    for _ in range(iters):
        if fc > fd: b, d, fd = d, c, fc; c = b - q*(b - a); fc = f(c)
        else: a, c, fc = c, d, fd; d = a + q*(b - a); fd = f(d)
    z = (a + b) / 2
    return z, f(z)

def loglik(xs, flags, k, lam):
    ans = mp.mpf(0)
    for x, e in zip(xs, flags):
        if x == 0: continue
        u = (x/lam)**k; ans -= u
        if e: ans += mp.log(k/lam) + (k - 1)*mp.log(x/lam)
    return ans

def samples():
    for scale in [1.0, 1e-200, 1e200]:
        for label, n, nc in [('0pct', 10, 0), ('30pct', 10, 3), ('90pct', 10, 9)]:
            vals = [scale*(1 + rng.random()*3) for _ in range(n)]
            yield label, scale, vals, [i >= nc for i in range(n)]
        yield 'cluster_above', scale, [2*scale]*3 + [3*scale, 5*scale], [True]*3 + [False]*2

cases = []
for label, scale, vals, flags in samples():
    xs = [mp.mpf(v) for v in vals]; s = mp.mpf(scale)
    # both free: outer log shape, inner log(scale / s)
    prof = lambda lk: golden(lambda ls: loglik(xs, flags, mp.exp(lk), s*mp.exp(ls)), -15, 15)
    lk, ll = golden(lambda lk: prof(lk)[1], -6, 6)
    ls, _ = prof(lk)
    assert -5.9 < lk < 5.9 and -14.9 < ls < 14.9
    cases.append(dict(kind='free', label=label, scale=scale, held=None, lower=vals, exact=flags,
                      shape=str(mp.exp(lk)), coef=str(s*mp.exp(ls)), logLik=str(ll)))
    # scale held at 2 * s: one golden section on log shape
    h = 2*s
    lk, ll = golden(lambda lk: loglik(xs, flags, mp.exp(lk), h), -6, 6)
    assert -5.9 < lk < 5.9
    cases.append(dict(kind='scale_held', label=label, scale=scale, held=2*scale, lower=vals, exact=flags,
                      shape=str(mp.exp(lk)), coef=str(h), logLik=str(ll)))

(OUT/'oracle_weibull_free.json').write_text(json.dumps(dict(dps=30, seed=20261111,
    method='nested golden sections on the censored log likelihood', cases=cases), indent=2) + '\n')
L = ['// Generated by dev/research/evaluations/2026-11-11-cens-easy-data/oracle_weibull_free.py',
     '#pragma once', '#include <cmath>', '#include <vector>', 'namespace censored_reference_weibull_free {',
     'struct Case { const char* kind; const char* label; double held, shape, scale, logLik; std::vector<double> lower; std::vector<int> exact; };',
     'inline std::vector<Case> cases() { return {']
for c in cases:
    L.append('{"%s","%s",%s,%r,%r,%r,{%s},{%s}},' % (c['kind'], c['label'],
        'NAN' if c['held'] is None else repr(c['held']), float(c['shape']), float(c['coef']), float(c['logLik']),
        ','.join(map(repr, c['lower'])), ','.join(str(int(f)) for f in c['exact'])))
L += ['}; }', '} // namespace censored_reference_weibull_free']
(ROOT/'univariateML-cpp/tests/censored_reference_weibull_free.hpp').write_text('\n'.join(L) + '\n')
print(len(cases), 'cases')
