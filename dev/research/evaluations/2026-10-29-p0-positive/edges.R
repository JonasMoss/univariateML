# Boundary, support, held-value, and partially matched argument probes.
library(univariateML,lib.loc="/tmp/umvl-p0lib")
set.seed(20261029)
rows<-list(); add<-function(test,result) rows[[length(rows)+1]]<<-data.frame(test,result=as.character(result))
x<-c(.5,1,3); levy_shape<-length(x)/sum(1/x)
o<-optimize(function(z) -sum(actuar::dinvgauss(x,mean=Inf,shape=exp(z),log=TRUE)),c(-10,10),tol=1e-12)
add("levy_held_mean_inf_shape_analytic",levy_shape)
add("levy_held_mean_inf_shape_oracle",exp(o$minimum))
stopifnot(abs(log(exp(o$minimum)/levy_shape))<1e-6)
add("levy_cdf_at_1",actuar::pinvgauss(1,mean=Inf,shape=4))
add("lnorm_sd0_density_at_and_away",paste(dlnorm(c(1,2),0,0),collapse=";"))
add("lnorm_sd0_sampler",paste(rlnorm(3,0,0),collapse=";"))
add("gamma_shape0_sampler",paste(rgamma(3,shape=0),collapse=";"))
add("invgamma_beta0_sampler",paste(extraDistr::rinvgamma(3,alpha=3,beta=0),collapse=";"))
add("power_endpoint_density",extraDistr::dpower(1,alpha=1,beta=2))
add("pareto_endpoint_density",extraDistr::dpareto(1,a=2,b=1))
px<-c(1,2,4); pa<-length(px)/sum(log(px/min(px)))
po<-optimize(function(z) -sum(extraDistr::dpareto(px,a=exp(z),b=min(px),log=TRUE)),c(-10,10),tol=1e-12)
add("pareto_joint_endpoint",min(px));add("pareto_joint_shape_analytic",pa)
add("pareto_joint_shape_oracle",exp(po$minimum))
stopifnot(abs(log(pa/exp(po$minimum)))<1e-6)
add("pareto_held_shape_endpoint",min(px))
add("pareto_invalid_held_endpoint_likelihood",prod(extraDistr::dpareto(px,a=2,b=2)))
wx<-c(.25,.5,1); wa<-2; wb<-length(wx)/sum(log(wa/wx))
wo<-optimize(function(z) -sum(extraDistr::dpower(wx,alpha=wa,beta=exp(z),log=TRUE)),c(-10,10),tol=1e-12)
add("power_held_endpoint_shape_analytic",wb);add("power_held_endpoint_shape_oracle",exp(wo$minimum))
add("power_invalid_held_endpoint_likelihood",prod(extraDistr::dpower(wx,alpha=max(wx),beta=2)))
stopifnot(abs(log(wb/exp(wo$minimum)))<1e-6)
for(id in c("weibull","invweibull","lomax","invpareto")) {
 n<-paste0("ml",id); z<-simulate_default(n,100)
 h<-switch(id,weibull=list(shape=2),invweibull=list(shape=2),lomax=list(lambda=1),invpareto=list(scale=1))
 fit<-tryCatch(do.call(get(n),c(list(x=z),h)),error=function(e)e)
 add(paste0(id,"_partial_match_fixed"),if(inherits(fit,"error")) conditionMessage(fit) else paste(attr(fit,"fixed"),collapse="+"))
 add(paste0(id,"_partial_match_estimate"),if(inherits(fit,"error")) "error" else as.numeric(fit[[names(h)]]))
}
x<-c(.2,.5,1,2,3); fit<-mlsgomp(x,eta=0)
o<-optimize(function(z) -sum(dsgomp(x,b=exp(z),eta=0,log=TRUE)),c(-10,10),tol=1e-12)
add("sgomp_eta0_package_loglik",as.numeric(logLik(fit)))
add("sgomp_eta0_oracle_loglik",-o$objective)
stopifnot(abs(as.numeric(logLik(fit))+o$objective)<1e-6*length(x))
fit<-mlsgomp(rep(0,5),b=1)
add("sgomp_all_zero_held_b_eta",as.numeric(fit[["eta"]]))
stopifnot(fit[["eta"]]==0)
write.csv(do.call(rbind,rows),"dev/research/evaluations/2026-10-29-p0-positive/edges.csv",row.names=FALSE)
print(do.call(rbind,rows),row.names=FALSE)
