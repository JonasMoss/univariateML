# Generate package/R/ml00_metadata.R (univariateML_metadata, generated_models,
# univariateML_samplers) from the per-distribution metadata.
# Run from univariateML/ via `just gen`.

dist_dir <- Sys.getenv(
  "UMVL_DOSSIER_DIR",
  "../cppunivariate/include/cppunivariate/distributions"
)
pkg_r_dir <- Sys.getenv("UMVL_PKG_R_DIR", "package/R")

source(file.path("scripts", "load_distributions.R"))
models <- load_distributions(dist_dir)

line <- function(...) paste0(..., collapse = "")

emit_bound <- function(v) if (is.infinite(v)) (if (v > 0) "Inf" else "-Inf") else format(v, digits = 17)

emit_support <- function(s) {
  lower <- if (is.null(s$lower)) "-Inf" else emit_bound(s$lower)
  upper <- if (is.null(s$upper)) "Inf" else emit_bound(s$upper)
  closed_vals <- if (is.null(s$closed)) c(FALSE, FALSE) else as.logical(unlist(s$closed))
  closed <- paste0("c(", paste(ifelse(closed_vals, "TRUE", "FALSE"), collapse = ", "), ")")
  type <- if (!is.null(s$type)) s$type else "R"
  line("list(bounds = c(", lower, ", ", upper, "), closed = ", closed, ", type = \"", type, "\")")
}

emit_params <- function(params) {
  names <- vapply(params, function(p) p$name, character(1))
  defaults <- vapply(params, function(p) p$default, numeric(1))
  list(
    names_vec = paste0("c(\"", paste(names, collapse = "\", \""), "\")"),
    defaults_vec = paste0("c(", paste(defaults, collapse = ", "), ")")
  )
}

generated_names <- paste0("ml", names(models))
samplers <- vapply(models, function(m) if (is.null(m$sampler)) NA_character_ else m$sampler,
                   character(1))

blocks <- c(
  "# This file is auto-generated by scripts/codegen_metadata.R",
  "# Do not edit by hand.",
  "",
  paste0("generated_models <- c(\"", paste0(generated_names, collapse = "\", \""), "\")"),
  "",
  "# Reference samplers (pkg::fn), used by dev tooling such as notes/ml-behaviour-sweep.R.",
  "univariateML_samplers <- c(",
  paste0("  ", generated_names, " = \"", samplers, "\"",
         c(rep(",", length(samplers) - 1L), "")),
  ")",
  "",
  "univariateML_metadata <- list()",
  ""
)

for (m in models) {
  param_info <- emit_params(m$params)
  blocks <- c(
    blocks,
    line("univariateML_metadata$ml", m$id, " <- list("),
    line("  model = \"", m$name, "\","),
    line("  density = \"", m$density, "\","),
    line("  support = ", emit_support(m$support), ","),
    line("  names = ", param_info$names_vec, ","),
    line("  default = ", param_info$defaults_vec),
    ")",
    ""
  )
}

dir.create(pkg_r_dir, recursive = TRUE, showWarnings = FALSE)
writeLines(blocks, file.path(pkg_r_dir, "ml00_metadata.R"))
