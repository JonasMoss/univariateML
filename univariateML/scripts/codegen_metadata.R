# Generate package/R/ml00_metadata.R (univariateML_metadata, generated_models,
# univariateML_samplers, univariateML_args) from the per-distribution metadata.
# Run from univariateML/ via `just gen`.

dist_dir <- Sys.getenv(
  "UMVL_DOSSIER_DIR",
  "../cppunivariate/include/cppunivariate/distributions"
)
pkg_r_dir <- Sys.getenv("UMVL_PKG_R_DIR", "package/R")

source(file.path("scripts", "load_distributions.R"))
models <- load_distributions(dist_dir)

line <- function(...) paste0(..., collapse = "")

emit_bound <- function(v) if (is.infinite(v)) (if (v > 0) "Inf" else "-Inf") else format(v, digits = 17)

emit_support <- function(s) {
  bounds <- list(s$lower, s$upper)
  dynamic <- vapply(bounds, is.character, logical(1))
  envelope <- bounds
  envelope[dynamic] <- list(-Inf, Inf)[dynamic]
  lower <- emit_bound(envelope[[1]])
  upper <- emit_bound(envelope[[2]])
  closed_vals <- as.logical(unlist(s$closed))
  # A coefficient-dependent endpoint has no pre-fit bound.
  check_closed <- closed_vals
  check_closed[dynamic] <- FALSE
  closed <- paste0("c(", paste(ifelse(check_closed, "TRUE", "FALSE"), collapse = ", "), ")")
  expr <- paste(deparse(bounds), collapse = " ")
  limits <- paste(deparse(s$endpoint_log_density), collapse = " ")
  line("list(bounds = c(", lower, ", ", upper, "), closed = ", closed,
       ", type = \"", s$type, "\", expressions = ", expr,
       ", endpoint_closed = ", paste(deparse(closed_vals), collapse = " "),
       ", endpoint_log_density = ", limits, ")")
}

emit_params <- function(params) {
  names <- vapply(params, function(p) p$name, character(1))
  defaults <- vapply(params, function(p) p$simulate, numeric(1))
  list(
    names_vec = paste0("c(\"", paste(names, collapse = "\", \""), "\")"),
    defaults_vec = paste0("c(", paste(defaults, collapse = ", "), ")")
  )
}

emit_args <- function(models) {
  with_args <- Filter(function(m) !is.null(m$args), models)
  if (!length(with_args)) return(character())
  entries <- vapply(with_args, function(m) {
    for (expr in m$args) {
      parsed <- tryCatch(parse(text = expr), error = function(e) NULL)
      if (is.null(parsed) || length(parsed) != 1L ||
          length(setdiff(all.vars(parsed), vapply(m$params, function(p) p$name, character(1))))) {
        stop("codegen_metadata: ", m$id, ": invalid r.args expression ", expr)
      }
    }
    line("  ml", m$id, " = c(", paste0(encodeString(names(m$args), quote='"'), " = ", encodeString(m$args, quote='"'), collapse = ", "), ")")
  }, character(1))
  paste0(entries, c(rep(",", length(entries) - 1L), ""))
}

emit_shifts <- function(models) {
  shifted <- Filter(function(m) !is.null(m$shift), models)
  entries <- vapply(shifted, function(m) {
    if (length(m$shift) != 1L || !m$shift %in% vapply(m$params, function(p) p$name, character(1)))
      stop("codegen_metadata: ", m$id, ": r.shift must name a coefficient")
    line("  ml", m$id, " = ", encodeString(m$shift, quote = '"'))
  }, character(1))
  if (length(entries)) paste0(entries, c(rep(",", length(entries) - 1L), "")) else character()
}

generated_names <- paste0("ml", names(models))
samplers <- vapply(models, function(m) if (is.null(m$sampler)) NA_character_ else m$sampler,
                   character(1))

blocks <- c(
  "# This file is auto-generated by scripts/codegen_metadata.R",
  "# Do not edit by hand.",
  "",
  paste0("generated_models <- c(\"", paste0(generated_names, collapse = "\", \""), "\")"),
  "",
  "# Reference samplers (pkg::fn), used by dev tooling such as notes/ml-behaviour-sweep.R.",
  "univariateML_samplers <- c(",
  paste0("  ", generated_names, " = \"", samplers, "\"",
         c(rep(",", length(samplers) - 1L), "")),
  ")",
  "",
  "# Argument maps (reference-function argument = coefficient) from README r.args,",
  "# for models whose d/p/q/r do not take the coefficient names.",
  "univariateML_args <- list(",
  emit_args(models),
  ")",
  "",
  "univariateML_shifts <- list(",
  emit_shifts(models),
  ")",
  "",
  "univariateML_metadata <- list()",
  ""
)

for (m in models) {
  param_info <- emit_params(m$params)
  blocks <- c(
    blocks,
    line("univariateML_metadata$ml", m$id, " <- list("),
    line("  model = \"", m$name, "\","),
    line("  density = \"", m$density, "\","),
    line("  support = ", emit_support(m$support), ","),
    line("  names = ", param_info$names_vec, ","),
    line("  simulate = ", param_info$defaults_vec, ","),
    line("  params = ", paste(deparse(m$params, width.cutoff=500L), collapse=" "), ","),
    line("  required = ", paste(deparse(vapply(Filter(function(p) p$required, m$params), `[[`, "", "name")), collapse=" "), ","),
    line("  holds = ", paste(deparse(m$holds, width.cutoff=500L), collapse=" "), ","),
    line("  limits = ", paste(deparse(m$limits, width.cutoff=500L), collapse=" "), ","),
    line("  fit_args = ", paste(deparse(m$fit_args, width.cutoff=500L), collapse=" ")),
    ")",
    ""
  )
}

dir.create(pkg_r_dir, recursive = TRUE, showWarnings = FALSE)
writeLines(blocks, file.path(pkg_r_dir, "ml00_metadata.R"))
